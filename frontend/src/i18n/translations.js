export function translate(language, key, vars) {
  const parts = key.split('.');
  let node = translations[language] || translations[DEFAULT_LANGUAGE];
  for (const part of parts) {
    node = node && node[part];
  }
  if (node === undefined) {
    // Fall back to English rather than showing a raw key if a translation is missing.
    node = parts.reduce((acc, part) => acc && acc[part], translations[DEFAULT_LANGUAGE]);
  }
  if (typeof node !== 'string') return key;
  if (!vars) return node;
  return Object.keys(vars).reduce((str, varKey) => str.replaceAll(`{${varKey}}`, String(vars[varKey])), node);
}
